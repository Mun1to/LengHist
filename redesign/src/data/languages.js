export function matchesFilter(lang, filter) {
  if (!filter || filter.type === 'all') return true
  if (filter.type === 'cat') return lang.categories.includes(filter.value)
  if (filter.type === 'fame') return lang.fame === filter.value
  if (filter.type === 'recent') return lang.year >= 2009
  return true
}
